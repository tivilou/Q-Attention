"""Native cached-replay sample-trace.v2, using the pinned project validator."""
from pathlib import Path
import hashlib,json,sys
import numpy as np

def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def display(s):return dict(summary=s,default_view='human_summary',visible_fields=[],visualizations=[])
def axes(k):
    return dict(h=['word','hidden'],roles=['word','role'],mask=['word'],angles=['word','layer','wire','rotation'],
        effect_angles=['relation','layer','wire','rotation'],psi=['word','basis'],phi=['relation','basis'],
        values=['word','value'],utilities=['relation','word'],probability=['relation','word'],alpha=['relation','word'],
        normalizer=['relation','singleton'],decoder=['relation','value'],bias=['relation'],logits=['relation'],
        residual=['relation','basis'],target=['singleton']).get(k,['relation'])
def group(k):
    if k in ('h','roles','mask'):return 'data'
    if k=='target':return 'evaluation'
    if k=='logits':return 'generation'
    if k in ('g','variance','self','upper','gamma','cross','z','residual'):return 'diagnosis'
    return 'scoring'

def read_value(root,sample,key,coords):
    root=Path(root).resolve(); rep=next(x for x in sample['representations'] if x['id']==key)
    ref=rep['value_capture']['artifact_refs'][0];p=root/ref['path']
    assert p.resolve().is_relative_to(root) and not p.is_symlink() and sha(p)==ref['sha256']
    with np.load(p,allow_pickle=False) as z:a=z[key].copy()
    assert list(a.shape)==rep['shape'] and str(a.dtype)==rep['dtype'] and np.isfinite(a).all()
    assert isinstance(coords,list) and 1<=len(coords)<=64
    values=[]
    for c in coords:
        assert len(c)==a.ndim and all(type(i) is int and 0<=i<n for i,n in zip(c,a.shape))
        v=a[tuple(c)].item();values.append(dict(real=v.real,imag=v.imag) if isinstance(v,complex) else v)
    return values

def capture(root,split,ordinal,index,metadata,arrays,checkpoint_sha):
    root=Path(root); sid=f'native:selected:{split}:{ordinal}';name=f'{split}-{ordinal}.private.npz'
    np.savez_compressed(root/name,**arrays)
    ref=dict(path=name,sha256=sha(root/name),bytes=(root/name).stat().st_size,visibility='private')
    reps=[];groups={g:[] for g in ('data','scoring','generation','diagnosis','evaluation')}
    for k,a in sorted(arrays.items()):
        assert len(axes(k))==a.ndim and np.isfinite(a).all();g=group(k);groups[g].append(k)
        reps.append(dict(id=k,stage_id=g,status='observed',meaning=k+' complete detached cached/native/diagnostic value',
            shape=list(a.shape),dtype=str(a.dtype),axis_semantics=axes(k),artifact_refs=[ref],display=display(k),
            value_capture=dict(status='complete',shape=list(a.shape),logical_element_count=int(a.size),stored_element_count=int(a.size),artifact_refs=[ref],
                reader_projection=dict(status='available',kind='coordinate_inspector',coordinate_access='arbitrary',
                    reader_ref='trace_io.py read_value '+sid+' '+k,source_sha256=[ref['sha256']]))))
    links=dict(data=['artifact:pinned_train_cache','artifact:pinned_cache_metadata'],
        scoring=['h','roles','mask','external:pinned_selected_checkpoint'],generation=['alpha','utilities','bias'],
        diagnosis=['psi','phi','probability','alpha','utilities','normalizer'],evaluation=['logits','artifact:pinned_train_targets'])
    stages=[]
    for j,g in enumerate(groups):
        stages.append(dict(stage_id=g,stage=g,canonical_stage=g,lane='replay',status='observed',step=j,checkpoint='selected',
            purpose=g+' in frozen cached TRAIN replay; no fitting',input_refs=links[g],output_refs=groups[g],artifact_refs=[ref],display=display(g),
            target_access='post_generation_only' if g=='evaluation' else 'not_available'))
    for j,g in enumerate(('preprocess','training'),len(stages)):
        stages.append(dict(stage_id=g,stage=g,canonical_stage=g,lane='replay',status='unavailable',step=j,
            purpose='Inherited immutable upstream production; no replay in this diagnostic',reason='Original encoder/training trajectory not generated by this run',
            input_refs=[],output_refs=[],display=display('Unavailable upstream trajectory')))
    return dict(sample_id=sid,lane='replay',split=split,checkpoint='selected',roles=dict(
        source_sample=dict(cache_index=index,metadata=metadata),sequence_or_features=dict(cache='pinned TRAIN word features'),
        target_or_gold=dict(value=int(arrays['target'][0]),boundary='post_generation_only'),
        prediction=dict(value=int(arrays['logits'].argmax())),provenance=dict(checkpoint_sha256=checkpoint_sha,reader_source_sha256=sha(__file__))),
        stages=stages,representations=reps)

def close(root,samples,cfg,config_sha,validator_dir):
    root=Path(root);sys.path.insert(0,str(validator_dir))
    from validate_sample_trace_v2 import validate,STAGES
    required=[r['id'] for r in samples[0]['representations']]
    payload=dict(schema_version='sample-trace.v2',trace_id=cfg['profile'],trace_completeness='complete',
        experiment=dict(run_id=cfg['profile'],dataset='Re-TACRED TRAIN cached replay only',code_revision=cfg['fixed_inputs']['native_code_sha256'],
            config_sha256=config_sha,model_identity='Fixed original selected native Q; inherited upstream trajectory unavailable',seed=13),
        sample_selection=dict(rule='First4 frozen fit and first4 frozen assessment cohort rows, before labels',population_scope='8 cached inference/derivative cases; not original encoder/training execution',
            selected_count=len(samples),selected_sample_ids=[s['sample_id'] for s in samples]),
        task_contract=dict(task_type='Frozen native-Q cached inference and fixed-C derivative diagnostic',
            required_roles=['source_sample','sequence_or_features','target_or_gold','prediction','provenance'],required_representations=required,
            required_value_representations=required,required_splits=['fit','assessment'],required_checkpoints=['selected'],required_lanes=['replay'],
            checkpoint_policy='Inherited epoch17 selected checkpoint; no trajectory or end-to-end encoder certification'),
        coverage={g:'observed' if g in ('data','scoring','generation','diagnosis','evaluation') else 'unavailable' if g in ('preprocess','training') else 'not_applicable' for g in STAGES},samples=samples)
    errors,warnings=validate(payload,require_complete=True);assert not errors,errors
    count=elements=0
    for s in samples:
        for r in s['representations']:
            ref=r['artifact_refs'][0]
            with np.load(root/ref['path'],allow_pickle=False) as z:a=z[r['id']].copy()
            coords=[list(map(int,np.unravel_index(k,a.shape))) for k in sorted({0,a.size//2,a.size-1})]
            values=read_value(root,s,r['id'],coords)
            for c,v in zip(coords,values):
                if isinstance(v,dict):v=complex(v['real'],v['imag'])
                assert v==a[tuple(c)].item();count+=1
            elements+=a.size
    p=root/'sample-trace.v2.private.json';p.write_text(json.dumps(payload,indent=2,allow_nan=False)+'\n')
    return dict(schema='sample-trace.v2',schema_sha256=sha(Path(validator_dir)/'sample-trace.v2.schema.json'),
        validator_sha256=sha(Path(validator_dir)/'validate_sample_trace_v2.py'),trace_sha256=sha(p),
        samples=len(samples),representations=sum(len(s['representations']) for s in samples),coordinate_reads=count,elements=int(elements),
        structural_errors=errors,warnings=warnings,completeness='complete for declared cached replay; upstream encoder/training unavailable',
        reader_sha256=sha(__file__),private_arrays_downloaded=False)
